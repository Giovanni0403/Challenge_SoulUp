DROP TABLE T_ECO_VIAGEM CASCADE CONSTRAINTS;
DROP TABLE T_ECO_USUARIO CASCADE CONSTRAINTS;

-- Usuário: quem registra as viagens (1 usuário : N viagens)
CREATE TABLE T_ECO_USUARIO (
    ID_USUARIO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO   VARCHAR2(100) NOT NULL,
    DS_EMAIL     VARCHAR2(120) NOT NULL,
    DT_CADASTRO  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ECO_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UN_ECO_USUARIO_EMAIL UNIQUE (DS_EMAIL)
);

-- Viagem: trajeto feito de transporte público
CREATE TABLE T_ECO_VIAGEM (
    ID_VIAGEM        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO       NUMBER        NOT NULL,
    DS_ORIGEM        VARCHAR2(80)  NOT NULL,
    DS_DESTINO       VARCHAR2(80)  NOT NULL,
    TP_TRANSPORTE    VARCHAR2(10)  NOT NULL,
    NR_DISTANCIA_KM  NUMBER(6,2)   NOT NULL,
    DT_VIAGEM        DATE          NOT NULL,
    CONSTRAINT PK_ECO_VIAGEM PRIMARY KEY (ID_VIAGEM),
    CONSTRAINT FK_ECO_VIAGEM_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_ECO_USUARIO (ID_USUARIO),
    CONSTRAINT CK_ECO_VIAGEM_TRANSPORTE CHECK (TP_TRANSPORTE IN ('ONIBUS', 'METRO', 'TREM')),
    CONSTRAINT CK_ECO_VIAGEM_DISTANCIA CHECK (NR_DISTANCIA_KM > 0 AND NR_DISTANCIA_KM <= 500)
);

